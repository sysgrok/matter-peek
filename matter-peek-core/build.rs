//! Generates the data model schema (see `src/controller/schema.rs`) from the
//! Matter IDL rs-matter's clusters are generated from: the names and types of
//! every cluster's attributes and commands.

fn main() {
    #[cfg(feature = "controller")]
    schema::generate();
}

/// The schema, for the controller.
#[cfg(feature = "controller")]
mod schema {
    use std::collections::BTreeSet;
    use std::env;
    use std::fmt::Write as _;
    use std::fs;
    use std::path::PathBuf;

    use rs_matter_codegen::ast::{
        ApiMaturity, Bitmap, Cluster, DataType, Entities, Enum, Idl, Struct, StructField,
        StructType,
    };

    /// The response of a command that answers with a status only.
    const NO_RESPONSE: &str = "DefaultSuccess";

    pub fn generate() {
        let idl = rs_matter_codegen::parse_idl();
        let out = PathBuf::from(env::var("OUT_DIR").unwrap()).join("schema.rs");

        fs::write(out, statics(&idl)).unwrap();
    }

    /// The statics of the schema: every cluster, and the enums, bitmaps and
    /// structs its values use.
    fn statics(idl: &Idl) -> String {
        let mut types = Types::default();
        let mut clusters: Vec<&Cluster> = idl
            .clusters
            .iter()
            .filter(|c| c.maturity != ApiMaturity::Internal)
            .collect();
        clusters.sort_by_key(|c| c.code);

        let mut list = String::from("pub static CLUSTERS: &[ClusterSchema] = &[\n");
        for cluster in clusters {
            let scope = Scope {
                cluster,
                globals: &idl.globals,
            };
            list.push_str(&cluster_schema(&scope, &mut types));
        }
        list.push_str("];\n");

        let mut code = String::from("// Generated by build.rs from the Matter IDL.\n\n");
        code.push_str(&list);
        code.push_str(&types.statics);
        code
    }

    fn cluster_schema(scope: &Scope, types: &mut Types) -> String {
        let c = scope.cluster;

        let mut attributes = String::new();
        for a in &c.attributes {
            let f = &a.field.field;
            writeln!(
                attributes,
                "AttrSchema {{ id: {}, name: {:?}, value: {}, writable: {}, timed: {} }},",
                f.code,
                pascal(&f.id),
                value(&a.field, scope, types),
                !a.is_read_only,
                a.is_timed_write,
            )
            .unwrap();
        }

        let mut commands = String::new();
        for cmd in &c.commands {
            let request = cmd
                .input
                .as_deref()
                .and_then(|input| scope.structure(input))
                .map(|s| fields(&s.fields, scope, types))
                .unwrap_or_else(|| "&[]".into());
            let response = match scope.structure(&cmd.output) {
                Some(s) if cmd.output != NO_RESPONSE => match s.struct_type {
                    StructType::Response(code) => format!(
                        "Some(RespSchema {{ id: {code}, name: {:?}, fields: {} }})",
                        s.id,
                        fields(&s.fields, scope, types)
                    ),
                    _ => "None".into(),
                },
                _ => "None".into(),
            };
            writeln!(
            commands,
            "CmdSchema {{ id: {}, name: {:?}, fields: {request}, response: {response}, timed: {} }},",
            cmd.code, cmd.id, cmd.is_timed,
        )
        .unwrap();
        }

        format!(
        "ClusterSchema {{ id: {}, name: {:?}, attributes: &[\n{attributes}], commands: &[\n{commands}] }},\n",
        c.code, c.id
    )
    }

    fn fields(fields: &[StructField], scope: &Scope, types: &mut Types) -> String {
        let mut out = String::from("&[");
        for f in fields {
            write!(
                out,
                "FieldSchema {{ tag: {}, name: {:?}, value: {} }}, ",
                f.field.code,
                pascal(&f.field.id),
                value(f, scope, types)
            )
            .unwrap();
        }
        out.push(']');
        out
    }

    fn value(f: &StructField, scope: &Scope, types: &mut Types) -> String {
        let dt = &f.field.data_type;

        format!(
            "ValueSchema {{ ty: {}, idl: {:?}, list: {}, nullable: {}, optional: {} }}",
            type_ref(dt, scope, types),
            dt.name,
            dt.is_list,
            f.is_nullable,
            f.is_optional
        )
    }

    /// The `TypeRef` of `dt`: a built-in type, or one of the cluster's or the
    /// shared enums, bitmaps and structs.
    fn type_ref(dt: &DataType, scope: &Scope, types: &mut Types) -> String {
        if let Some(builtin) = builtin(&dt.name) {
            return builtin.into();
        }

        if let Some((e, shared)) = scope.enumeration(&dt.name) {
            return format!(
                "TypeRef::Enum(&{})",
                types.enumeration(e, scope.owner(shared))
            );
        }
        if let Some((b, shared)) = scope.bitmap(&dt.name) {
            return format!("TypeRef::Bitmap(&{})", types.bitmap(b, scope.owner(shared)));
        }
        if let Some((s, shared)) = scope.structure_shared(&dt.name) {
            let name = types.structure_name(s, scope.owner(shared));
            if types.declared.insert(name.clone()) {
                let fields = fields(&s.fields, scope, types);
                writeln!(
                types.statics,
                "static {name}: StructSchema = StructSchema {{ name: {:?}, fields: {fields} }};",
                s.id
            )
                .unwrap();
            }
            return format!("TypeRef::Struct(&{name})");
        }

        panic!("{}: no type {}", scope.cluster.id, dt.name)
    }

    /// The built-in types, by their IDL names.
    fn builtin(name: &str) -> Option<&'static str> {
        Some(match name.to_ascii_lowercase().as_str() {
            "boolean" => "TypeRef::Bool",
            "single" => "TypeRef::Float",
            "double" => "TypeRef::Double",
            "char_string" | "long_char_string" => "TypeRef::Text",
            "octet_string" | "long_octet_string" | "ipadr" | "ipv4adr" | "ipv6adr" | "ipv6pre"
            | "hwadr" => "TypeRef::Octets",
            "int8u" | "enum8" | "bitmap8" | "priority" | "status" | "percent" | "action_id"
            | "namespace" | "tag" | "fabric_idx" => "TypeRef::UInt(8)",
            "int16u" | "enum16" | "bitmap16" | "percent100ths" | "group_id" | "endpoint_no"
            | "vendor_id" | "entry_idx" => "TypeRef::UInt(16)",
            "int24u" => "TypeRef::UInt(24)",
            "int32u" | "bitmap32" | "epoch_s" | "utc" | "elapsed_s" | "devtype_id"
            | "cluster_id" | "attrib_id" | "field_id" | "event_id" | "command_id" | "trans_id"
            | "data_ver" => "TypeRef::UInt(32)",
            "int40u" => "TypeRef::UInt(40)",
            "int48u" => "TypeRef::UInt(48)",
            "int56u" => "TypeRef::UInt(56)",
            "int64u" | "bitmap64" | "epoch_us" | "posix_ms" | "systime_us" | "systime_ms"
            | "node_id" | "fabric_id" | "event_no" => "TypeRef::UInt(64)",
            "int8s" => "TypeRef::Int(8)",
            "int16s" | "temperature" => "TypeRef::Int(16)",
            "int24s" => "TypeRef::Int(24)",
            "int32s" => "TypeRef::Int(32)",
            "int40s" => "TypeRef::Int(40)",
            "int48s" => "TypeRef::Int(48)",
            "int56s" => "TypeRef::Int(56)",
            "int64s" | "energy_mwh" | "energy_mvah" | "energy_mvarh" | "amperage_ma"
            | "power_mw" | "power_mva" | "power_mvar" | "voltage_mv" | "money" => {
                "TypeRef::Int(64)"
            }
            _ => return None,
        })
    }

    /// `name` as the spec writes it: `onOff` → `OnOff`.
    fn pascal(name: &str) -> String {
        let mut chars = name.chars();
        match chars.next() {
            Some(first) => first.to_uppercase().chain(chars).collect(),
            None => String::new(),
        }
    }

    /// An enum's or bitmap's entry as the spec names it: `kHeat` → `Heat`.
    fn entry_name(name: &str) -> &str {
        match name.strip_prefix('k') {
            Some(rest)
                if rest.starts_with(|c: char| c.is_ascii_uppercase() || c.is_ascii_digit()) =>
            {
                rest
            }
            _ => name,
        }
    }

    /// `name` as a static's name.
    fn screaming(name: &str) -> String {
        let mut out = String::new();
        for (i, c) in name.chars().enumerate() {
            if c.is_ascii_uppercase() && i > 0 {
                out.push('_');
            }
            out.push(c.to_ascii_uppercase());
        }
        out
    }

    /// The entities a cluster's types are looked up in: its own, then the
    /// shared ones.
    struct Scope<'a> {
        cluster: &'a Cluster,
        globals: &'a Entities,
    }

    impl Scope<'_> {
        fn structure(&self, name: &str) -> Option<&Struct> {
            self.structure_shared(name).map(|(s, _)| s)
        }

        fn structure_shared(&self, name: &str) -> Option<(&Struct, bool)> {
            find(
                &self.cluster.entities.structs,
                &self.globals.structs,
                name,
                |s| &s.id,
            )
        }

        fn enumeration(&self, name: &str) -> Option<(&Enum, bool)> {
            find(
                &self.cluster.entities.enums,
                &self.globals.enums,
                name,
                |e| &e.id,
            )
        }

        fn bitmap(&self, name: &str) -> Option<(&Bitmap, bool)> {
            find(
                &self.cluster.entities.bitmaps,
                &self.globals.bitmaps,
                name,
                |b| &b.id,
            )
        }

        /// Who owns an entity: the cluster, or nobody if it is shared.
        fn owner(&self, shared: bool) -> Option<&str> {
            (!shared).then_some(self.cluster.id.as_str())
        }
    }

    /// The enums, bitmaps and structs declared so far, as statics.
    #[derive(Default)]
    struct Types {
        statics: String,
        declared: BTreeSet<String>,
    }

    impl Types {
        fn enumeration(&mut self, e: &Enum, owner: Option<&str>) -> String {
            let name = static_name("E", owner, &e.id);
            if self.declared.insert(name.clone()) {
                let mut values = String::new();
                for entry in &e.entries {
                    write!(values, "({}, {:?}), ", entry.code, entry_name(&entry.id)).unwrap();
                }
                writeln!(
                    self.statics,
                    "static {name}: EnumSchema = EnumSchema {{ name: {:?}, values: &[{values}] }};",
                    e.id
                )
                .unwrap();
            }
            name
        }

        fn bitmap(&mut self, b: &Bitmap, owner: Option<&str>) -> String {
            let name = static_name("B", owner, &b.id);
            if self.declared.insert(name.clone()) {
                let mut bits = String::new();
                for entry in &b.entries {
                    write!(bits, "({}, {:?}), ", entry.code, entry_name(&entry.id)).unwrap();
                }
                writeln!(
                    self.statics,
                    "static {name}: BitmapSchema = BitmapSchema {{ name: {:?}, bits: &[{bits}] }};",
                    b.id
                )
                .unwrap();
            }
            name
        }

        fn structure_name(&self, s: &Struct, owner: Option<&str>) -> String {
            static_name("S", owner, &s.id)
        }
    }

    fn static_name(kind: &str, owner: Option<&str>, id: &str) -> String {
        match owner {
            Some(owner) => format!("{kind}_{}__{}", screaming(owner), screaming(id)),
            None => format!("{kind}_{}", screaming(id)),
        }
    }

    /// An entity named `name`: the cluster's own, else a shared one (`true`).
    fn find<'a, T>(
        own: &'a [T],
        shared: &'a [T],
        name: &str,
        id: impl Fn(&T) -> &String,
    ) -> Option<(&'a T, bool)> {
        own.iter()
            .find(|t| id(t) == name)
            .map(|t| (t, false))
            .or_else(|| shared.iter().find(|t| id(t) == name).map(|t| (t, true)))
    }
}
