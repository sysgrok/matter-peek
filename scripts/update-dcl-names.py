#!/usr/bin/env python3
"""Regenerate matter-peek-core/src/api/display/dcl.rs: the vendor and product names of the
CSA Distributed Compliance Ledger (DCL), the registry of Matter vendors and
certified products.

    python3 scripts/update-dcl-names.py
"""

import json
import pathlib
import urllib.parse
import unicodedata
import urllib.request

DCL = "https://on.dcl.csa-iot.org/dcl"
OUT = pathlib.Path(__file__).resolve().parent.parent / "matter-peek-core/src/api/display/dcl.rs"


def fetch(path, key):
    """All the entries of a DCL list, following its pagination."""
    entries, next_key = [], None
    while True:
        url = f"{DCL}/{path}?pagination.limit=10000"
        if next_key:
            url += f"&pagination.key={urllib.parse.quote(next_key)}"
        with urllib.request.urlopen(url, timeout=120) as resp:
            page = json.load(resp)
        entries += page.get(key, [])
        next_key = (page.get("pagination") or {}).get("next_key")
        if not next_key:
            return entries


def clean(name):
    """`name` without invisible characters (zero-width spaces, say), trimmed."""
    return "".join(c for c in name or "" if unicodedata.category(c) not in ("Cc", "Cf")).strip()


def literal(s):
    """A Rust string literal."""
    out = []
    for c in s:
        if c in '\\"':
            out.append("\\" + c)
        elif c == "\n":
            out.append("\\n")
        elif ord(c) < 0x20 or c == "\x7f":
            out.append(f"\\u{{{ord(c):x}}}")
        else:
            out.append(c)
    return '"' + "".join(out) + '"'


def main():
    vendors = {}
    for v in fetch("vendorinfo/vendors", "vendorInfo"):
        name = clean(v.get("vendorName"))
        if name:
            vendors[v["vendorID"]] = name

    products = {}
    for m in fetch("model/models", "model"):
        name = clean(m.get("productName"))
        if name:
            products[(m["vid"], m["pid"])] = name

    lines = [
        "//! The vendor and product names of the CSA Distributed Compliance Ledger,",
        "//! generated by `scripts/update-dcl-names.py`: do not edit.",
        "",
        "/// Vendor IDs and names, sorted by ID.",
        "pub(super) static VENDORS: &[(u16, &str)] = &[",
    ]
    lines += [f"    (0x{vid:04X}, {literal(name)})," for vid, name in sorted(vendors.items())]
    lines += [
        "];",
        "",
        "/// Vendor and product IDs, and product names, sorted by the IDs.",
        "pub(super) static PRODUCTS: &[(u16, u16, &str)] = &[",
    ]
    lines += [
        f"    (0x{vid:04X}, 0x{pid:04X}, {literal(name)}),"
        for (vid, pid), name in sorted(products.items())
    ]
    lines += ["];", ""]

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{OUT}: {len(vendors)} vendors, {len(products)} products")


if __name__ == "__main__":
    main()
